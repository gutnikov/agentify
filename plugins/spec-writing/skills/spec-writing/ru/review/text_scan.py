WB = '[а-яa-z0-9]'


def compile_marker(m):
    """Маркер → (regex, isolated)."""
    if m.startswith('r:'):
        return re.compile(m[2:]), False
    isolated = m.startswith('!')
    if isolated:
        m = m[1:]
    m = m.lower().replace('ё', 'е')
    parts = []
    for tok in m.split():
        if tok in ('—', '-'):
            parts.append(r'\s*[—-]\s*')
            continue
        esc = re.escape(tok).replace(r'\*', WB + '*')
        parts.append(esc)
    body = r'\s+'.join(parts).replace(r'\s+\s*[—-]\s*\s+', r'\s*[—-]\s*')
    if isolated:
        return re.compile(r'(^[«"(—\s]*|[,(—]\s*)(' + body + r')(?=\s*[,)—]|\s*$)'), True
    return re.compile(r'(?<!' + WB + r')' + body + r'(?!' + WB + r')'), False


class Finder(object):
    def __init__(self, blocks):
        self.blocks = blocks
        self.findings = []
        self.claimed = {}

    def add(self, code, block, start, end, note='', claim=True, strength='strong'):
        for f in self.findings:
            if f['code'] == code and f['block'] == block.n and f.get('_span') and \
                    start < f['_span'][1] and end > f['_span'][0]:
                return
        if claim:
            key = (block.n,)
            for a, b in self.claimed.get(key, []):
                if start < b and end > a:
                    return
            self.claimed.setdefault(key, []).append((start, end))
        s = block.sent_of(start)
        sa, sb = block.sents[s - 1] if block.sents else (0, len(block.text))
        lo, hi = max(sa, start - 45), min(sb, end + 45)
        ctx = block.text[lo:start] + '[' + block.text[start:end] + ']' + block.text[end:hi]
        ctx = ('…' if lo > sa else '') + ctx.replace('\n', ' ').strip() + ('…' if hi < sb else '')
        self.findings.append(OrderedDict([
            ('code', code), ('title', TITLES.get(code, code)), ('block', block.n), ('sentence', s),
            ('line', block.line_of(start)), ('match', block.text[start:end].replace('\n', ' ')),
            ('context', ctx), ('note', note), ('strength', strength), ('_span', (start, end)),
        ]))

    def add_block(self, code, block, note):
        self.findings.append(OrderedDict([
            ('code', code), ('title', TITLES.get(code, code)), ('block', block.n), ('sentence', None),
            ('line', block.line), ('match', ''), ('context', block.text[:90].replace('\n', ' ') +
                                                   ('…' if len(block.text) > 90 else '')),
            ('note', note), ('strength', 'strong'),
        ]))

    def add_text(self, code, note):
        self.findings.append(OrderedDict([
            ('code', code), ('title', TITLES.get(code, code)), ('block', None), ('sentence', None),
            ('line', None), ('match', ''), ('context', 'весь текст'), ('note', note), ('strength', 'strong'),
        ]))


def iter_sentences(block):
    for i, (a, b) in enumerate(block.sents, 1):
        yield i, a, b, block.norm[a:b]


_COMPILED = {}


def scan_markers(fd, block, code, markers, claim=True, note=''):
    compiled = _COMPILED
    for tier in ('strong', 'weak'):
        for m in markers.get(tier, []):
            if m not in compiled:
                compiled[m] = compile_marker(m)
    for _, a, b, sent in iter_sentences(block):
        hits = []
        for tier in ('strong', 'weak'):
            for m in markers.get(tier, []):
                rx, iso = compiled[m]
                for mt in rx.finditer(sent):
                    s, e = (mt.span(2) if iso else mt.span())
                    hits.append((a + s, a + e, tier))
        strong = [h for h in hits if h[2] == 'strong']
        weak = [h for h in hits if h[2] == 'weak']
        use = strong + (weak if len(hits) >= 2 and weak else [])
        for s, e, tier in sorted(use):
            fd.add(code, block, s, e, note=note, claim=claim, strength=tier)


def scan(text):
    blocks = parse_blocks(text)
    fd = Finder(blocks)
    body = [b for b in blocks if b.kind in ('para', 'item', 'quote')]
    paras = [b for b in blocks if b.kind == 'para']
    headings = [b for b in blocks if b.kind == 'heading']

    # --- словарные коды (одно место — один код, в порядке приоритета)
    word_codes = ['T-HIDE', 'T-BS', 'T-PERSONAL', 'T-TERMS', 'W-PROP', 'W-CORP', 'W-CLICHE', 'W-BUREAU',
                  'W-INTRO', 'W-INTENS', 'W-EVAL', 'W-ZAUM', 'W-VAGUE', 'W-VAGUE-NUM', 'W-NOMINAL']
    for b in blocks:
        if b.kind in ('image',):
            continue
        for code in word_codes:
            scan_markers(fd, b, 'W-VAGUE' if code == 'W-VAGUE-NUM' else code, DICT[code])
        scan_markers(fd, b, 'P-INACTION', STATE_VERBS, claim=False)

    # --- плотность пустословия: 3+ маркера оценок и штампов в одном абзаце
    hollow_codes = ('W-EVAL', 'W-INTENS', 'W-CORP', 'W-CLICHE')
    for b in body:
        n = sum(1 for f in fd.findings if f['block'] == b.n and f['code'] in hollow_codes)
        if n >= 3:
            fd.add_block('M-HOLLOW', b, '%d маркеров оценок и штампов в абзаце: есть ли за ними факты?' % n)

    # --- вежливость: 2+ формулы в одном блоке
    pol = [compile_marker(m)[0] for m in POLITE]
    for b in body:
        hits = [mt.span() for rx in pol for mt in rx.finditer(b.norm)]
        if len(hits) >= 2:
            for s, e in sorted(hits):
                fd.add('W-POLITE', b, s, e, note='%d формулы вежливости в блоке' % len(hits), claim=False)

    # --- грамматика: причастия, деепричастия, страдательный залог
    for b in body:
        for i, a, e, sent in iter_sentences(b):
            for mt in PARTICIPLE.finditer(sent):
                lead = len(mt.group(0)) - len(mt.group(0).lstrip(', '))
                fd.add('W-PARTIC', b, a + mt.start() + lead, a + mt.end(), note='причастный оборот?', claim=False)
            for mt in GERUND.finditer(sent):
                s = mt.start() + (len(mt.group(0)) - len(mt.group(0).lstrip(', ')))
                fd.add('W-PARTIC', b, a + s, a + mt.end(), note='деепричастие?', claim=False)
            for mt in PASSIVE.finditer(sent):
                if mt.group(1) in PASSIVE_EXCLUDE:
                    continue
                fd.add('W-PASSIVE', b, a + mt.start(), a + mt.end(), claim=False)

    # --- предложения: длина, подчинение, союзы, парцелляция, перечисления
    for b in body:
        short_run = []
        for i, a, e, sent in iter_sentences(b):
            raw = b.text[a:e]
            words = WORD.findall(raw)
            commas = raw.count(',')
            subs = len(SUBORD.findall(sent)) + len(EXTRA_SUBORD.findall(sent))
            if len(words) >= 25 or commas >= 4:
                fd.add('SIGNAL-LONG', b, a, e, note='%d слов, %d запятых' % (len(words), commas), claim=False)
            if subs >= 3:
                fd.add('P-NESTED', b, a, e, note='%d подчинительных союзов/слов' % subs, claim=False)
            for mt in REPORTED.finditer(sent):
                fd.add('P-NESTED', b, a + mt.start(), a + mt.end(), note='косвенная речь или глагол мысли', claim=False)
            for rx in SPLITCONJ:
                for mt in rx.finditer(sent):
                    fd.add('P-SPLITCONJ', b, a + mt.start(), a + mt.end(), claim=False)
            glued = GLUED.search(sent)
            if glued:
                fd.add('P-GLUED', b, a, a + glued.end(), note='запятая между двумя предложениями?', claim=False)
            for mt in INLINE_LIST_MARK.finditer(sent):
                if commas >= 3:
                    fd.add('P-INLINELIST', b, a + mt.start(), a + mt.end(), note='%d запятых' % commas, claim=False)
            if re.match(r'^[«"(—\s]*котор', sent):
                fd.add('P-PARCEL', b, a, e, note='предложение начинается с «который»', claim=False)
            if len(words) <= 3:
                short_run.append((b, a, e))
            else:
                if len(short_run) >= 3:
                    fb, fa, fe = short_run[0]
                    fd.add('P-PARCEL', fb, fa, fe, note='%d очень коротких предложений подряд' % len(short_run), claim=False)
                short_run = []
        if len(short_run) >= 3:
            fb, fa, fe = short_run[0]
            fd.add('P-PARCEL', fb, fa, fe, note='%d очень коротких предложений подряд' % len(short_run), claim=False)

    # --- числа: наукообразные, бесполезные, вне опыта
    for b in body:
        for i, a, e, sent in iter_sentences(b):
            for rx in FAKENUM:
                for mt in rx.finditer(sent):
                    if not SOURCE.search(sent):
                        fd.add('T-NUMBERS', b, a + mt.start(), a + mt.end(), note='источник в предложении не назван',
                               claim=False)
            for m in NOUSE:
                rx = compile_marker(m)[0]
                for mt in rx.finditer(sent):
                    fd.add('M-FACTS', b, a + mt.start(), a + mt.end(), note='факт о компании: нужен ли он читателю?', claim=False)
            units = list(UNITS.finditer(sent))
            if units:
                fd.add('M-FACTS', b, a + units[0].start(), a + units[-1].end(),
                       note='характеристики в единицах: переведены ли в опыт читателя?', claim=False)

    # --- заголовки
    for h in headings:
        raw = h.text
        caps = [w for w in re.findall(r'\b[А-ЯЁA-Z]{2,}\b', raw) if w not in ACRONYMS and len(w) >= 3]
        if caps:
            fd.add_block('S-CLICKBAIT', h, 'слова прописными: ' + ', '.join(caps))
        if re.search(r'[!?]\s*[!?]|!\s*$|(?:\.\.\.|…)\s*$', raw):
            fd.add_block('S-CLICKBAIT', h, 'восклицание или многоточие в заголовке')
        for m in CLICKBAIT:
            rx = compile_marker(m)[0]
            mt = rx.search(h.norm)
            if mt:
                fd.add('S-CLICKBAIT', h, mt.start(), mt.end(), claim=False)
        if re.search(r'«[^»]*(?:\.\.\.|…)[^»]*»', raw) or re.search(r':\s*«[^»\s]+(?:\s+[^»\s]+){0,2}»\s*$', raw):
            fd.add_block('T-TITLE', h, 'обрезанная цитата в заголовке: смысл сохранён?')
        if re.search(r'\b[А-ЯЁ]{4,}!', raw):
            fd.add_block('T-TITLE', h, 'глагол прописными с восклицанием')
    title = headings[0] if headings and headings[0].n == 1 else None
    # короткому фрагменту, письму или посту заголовок не нужен (каталог, S-TITLE «Не ошибка, если»)
    if body and not title and sum(len(b.text) for b in body) >= 1000:
        fd.add_text('S-TITLE', 'у текста %d знаков нет заголовка (первый блок — не заголовок)' % sum(len(b.text) for b in body))

    # --- вступление и заключение
    content = [b for b in blocks if b.kind in ('para', 'quote', 'item')]
    if content:
        first = content[0]
        for m in INTRO_OPENERS:
            rx = compile_marker(m)[0]
            for mt in rx.finditer(first.norm):
                fd.add('S-INTRO', first, mt.start(), mt.end(), note='оборот в первом абзаце', claim=False)
        for last in content[-2:]:
            for m in OUTRO_CLOSERS:
                rx = compile_marker(m)[0]
                for mt in rx.finditer(last.norm):
                    fd.add('S-OUTRO', last, mt.start(), mt.end(), note='формула в конце текста', claim=False)

    # --- абзацы, подзаголовки, перечни
    total = sum(len(b.text) for b in body)
    for b in paras + [x for x in blocks if x.kind == 'quote']:
        if len(b.text) >= 600:
            fd.add_block('S-WALL', b, '%d знаков, %d предложений (≈ больше 8 строк в широкой колонке)' % (len(b.text), len(b.sents)))
    if total >= 1500 and len(paras) <= 2:
        fd.add_text('S-WALL', 'текст %d знаков почти без деления на абзацы (%d абзаца)' % (total, len(paras)))
    subheads = [h for h in headings if not (title and h.n == title.n)]
    if total >= 2000 and len(paras) >= 6 and not subheads:
        fd.add_text('S-SUBHEADS', 'текст %d знаков, %d абзацев без подзаголовков' % (total, len(paras)))
    if subheads:
        marks = [h.n for h in subheads] + [len(blocks) + 1]
        prev = subheads[0].n
        sections = []
        for nxt in marks[1:]:
            sections.append((prev, sum(1 for b in paras if prev < b.n < nxt)))
            prev = nxt
        before = sum(1 for b in paras if b.n < subheads[0].n)
        for start, cnt in sections:
            if cnt > 10:
                blk = blocks[start - 1]
                fd.add_block('S-SUBHEADS', blk, 'под подзаголовком %d абзацев (ориентир — один подзаголовок на 5–10)' % cnt)
        if before > 10:
            fd.add_text('S-SUBHEADS', 'до первого подзаголовка %d абзацев' % before)
        # план статьи (одни заголовки, без текста под большинством из них) — не перегруз
        filled = sum(1 for _, cnt in sections if cnt)
        if len(subheads) >= 3 and filled * 2 >= len(sections) and len(paras) / float(len(subheads)) < 2:
            fd.add_text('S-SUBHEADS', '%d подзаголовков на %d абзацев: перегруз подзаголовками?' % (len(subheads), len(paras)))

    runs, cur = [], []
    for b in blocks:
        if b.kind == 'item':
            cur.append(b)
        else:
            if cur:
                runs.append(cur)
            cur = []
    if cur:
        runs.append(cur)
    for run in runs:
        prev_block = blocks[run[0].n - 2] if run[0].n >= 2 else None
        if len(run) > 7:
            fd.add_block('S-LIST', run[0], 'в перечне %d пунктов' % len(run))
        for it in run:
            if len(it.text) > 300 or len(it.sents) > 2:
                fd.add_block('S-LIST', it, 'длинный пункт: %d знаков, %d предложений' % (len(it.text), len(it.sents)))
            mt = LIST_START_WEAK.search(it.norm.strip())
            if mt:
                fd.add_block('S-LIST', it, 'пункт начинается со связки «%s»: связный текст разрезан на пункты?' % mt.group(0))
        if prev_block is not None and prev_block.kind == 'para' and prev_block.text.rstrip().endswith(':'):
            words = WORD.findall(prev_block.text)
            if words and VERB_END.search(words[-1].lower()):
                fd.add_block('S-LIST', prev_block, 'перед перечнем нет обобщающего слова («…%s:»)' % words[-1])

    # --- утопленные ограничения
    for b in paras:
        if len(b.text) >= 500:
            cut = int(len(b.text) * 0.6)
            for mt in RESTRICT.finditer(b.norm):
                if mt.start() >= cut:
                    fd.add('S-BURIED', b, mt.start(), mt.end(), note='ограничение в конце длинного абзаца', claim=False)

    # --- примеры
    if total >= 2000 and not any(EXAMPLE_MARKERS.search(b.norm) for b in body):
        fd.add_text('M-NOEXAMPLE', 'в тексте %d знаков нет ни одного маркера примера («например», «допустим», «представьте»…)' % total)

    # --- иллюстрации
    has_visual = set(b.n for b in blocks if b.kind in ('image', 'table'))
    for b in blocks:
        for mt in IMAGE.finditer(b.text):
            alt, src = mt.group(1).lower(), mt.group(2).lower()
            if STOCK_WORDS.search(alt):
                fd.add('V-DECOR', b, mt.start(), mt.end(), note='alt похож на картинку «в тему»: %s' % alt, claim=False)
            if STOCK_SRC.search(src):
                fd.add('V-RIGHTS', b, mt.start(), mt.end(), note='источник похож на фотобанк или поисковик', claim=False)
            if not alt.strip():
                fd.add('V-DECOR', b, mt.start(), mt.end(), note='картинка без описания — проверить, что она показывает', claim=False)
    for b in paras:
        seq = len(SEQUENCE.findall(b.norm))
        ifs = len(re.findall(r'(?<![а-яa-z0-9])если(?![а-яa-z0-9])', b.norm))
        near = any(abs(b.n - n) <= 2 for n in has_visual)
        if (seq >= 4 or ifs >= 3) and not near:
            fd.add_block('V-NOSCHEME', b, '%d шагов-связок, %d «если»; схемы рядом нет' % (seq, ifs))

    return blocks, fd.findings


