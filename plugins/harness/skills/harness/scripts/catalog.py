#!/usr/bin/env python3
"""The loop-type catalog (../loop-types): build its index and validate it.

    python3 catalog.py index   write loop-types/index.yaml from the cards' frontmatter
    python3 catalog.py check   validate every card and fail if index.yaml is out of date

Group titles come from the "### <title> — `<group>/`" headings in loop-types/README.md.
A card's summary is the start of its Loop section: the first paragraph (with its list, if it leads into one),
without sentences about the source, at most 3 sentences.
No dependencies: frontmatter holds only scalars and flow lists; strings are written as JSON, which is valid YAML.
"""
import json
import pathlib
import re
import sys

CATALOG = pathlib.Path(__file__).resolve().parent.parent / "loop-types"
INDEX = CATALOG / "index.yaml"
FIELDS = ["qualities", "when", "initiator", "sync", "assesses", "stages", "speed"]
VOCAB = {
    "stages": {"edit", "local", "commit", "ci", "preview", "staging", "production", "scheduled", "task", "sprint",
               "continuous"},
    "speed": {"sub-second", "seconds", "minutes", "hours", "days", "weeks"},
    "when": {"before", "during", "after", "production"},
    "initiator": {"agent", "human", "rule", "schedule"},
    "sync": {"blocking", "async"},
    "assesses": {"intent", "plan", "result", "code", "action-risk"},
}
ITEM = re.compile(r"^\s*(\d+\.|-)\s+")


def frontmatter(text):
    m = re.match(r"^---\n(.*?)\n---\n", text, re.S)
    if not m:
        return None
    data = {}
    for line in m.group(1).splitlines():
        key, _, value = line.partition(":")
        value = value.strip()
        if value.startswith("["):
            data[key.strip()] = [v.strip() for v in value[1:-1].split(",") if v.strip()]
        else:
            data[key.strip()] = value[1:-1] if value.startswith('"') else value
    return data


def items(para):
    return [ITEM.sub("", l).strip().rstrip(".") for l in para.splitlines() if ITEM.match(l)]


def summary(text):
    m = re.search(r"^## Loop\n\n(.*?)(?=^## |\Z)", text, re.S | re.M)
    if not m:
        return ""
    paras = m.group(1).strip().split("\n\n")
    if ITEM.match(paras[0]):
        para = ". ".join(items(paras[0])) + "."
    else:
        para = " ".join(l.strip() for l in paras[0].splitlines())
        if para.endswith(":") and len(paras) > 1 and ITEM.match(paras[1]):
            para += " " + "; ".join(items(paras[1])) + "."
    sentences = re.split(r"(?<=[.!?])\s+(?=[A-Z\"`(])", para)
    keep = [s for s in sentences if not re.search(r"\b(the source|the research|the note|this card)\b", s, re.I)]
    return " ".join(keep[:3]) or sentences[0]


def groups():
    return re.findall(r"^### (.+?) — `([a-z]+)/`$", (CATALOG / "README.md").read_text(encoding="utf-8"), re.M)


def cards():
    return sorted(p for p in CATALOG.glob("*/*.md") if p.name != "README.md")


def build_index():
    out = ["# Generated by scripts/catalog.py from the frontmatter of loop-types/<group>/<id>.md.",
           "# Do not edit by hand: change the card, then run `python3 scripts/catalog.py index`.",
           "", "groups:"]
    order = []
    for title, group in groups():
        out.append("  %s: %s" % (group, json.dumps(title, ensure_ascii=False)))
        order.append(group)
    out += ["", "loop_types:"]
    for group in order:
        for path in sorted((CATALOG / group).glob("*.md")):
            if path.name == "README.md":
                continue
            text = path.read_text(encoding="utf-8")
            fm = frontmatter(text) or {}
            out.append("  - id: %s" % fm.get("id"))
            out.append("    title: %s" % json.dumps(fm.get("title"), ensure_ascii=False))
            out.append("    group: %s" % fm.get("group"))
            out.append("    path: %s" % path.relative_to(CATALOG))
            out.append("    summary: %s" % json.dumps(summary(text), ensure_ascii=False))
            for key in FIELDS:
                if key in fm:
                    v = fm[key]
                    out.append("    %s: %s" % (key, "[%s]" % ", ".join(v) if isinstance(v, list) else v))
    return "\n".join(out) + "\n"


def check():
    errors = []
    group_ids = [g for _, g in groups()]
    for path in cards():
        rel = path.relative_to(CATALOG)
        text = path.read_text(encoding="utf-8")
        fm = frontmatter(text)
        if fm is None:
            errors.append("%s: no frontmatter" % rel)
            continue
        human = path.parent.name == "human"
        if fm.get("id") != path.stem:
            errors.append("%s: id %r does not match the file name" % (rel, fm.get("id")))
        if fm.get("group") != path.parent.name:
            errors.append("%s: group %r does not match the folder" % (rel, fm.get("group")))
        if path.parent.name not in group_ids:
            errors.append("%s: folder has no heading in README.md" % rel)
        if "# %s\n" % fm.get("title") not in text:
            errors.append("%s: H1 does not match the title" % rel)
        for key, vocab in VOCAB.items():
            values = fm.get(key, [])
            for v in values if isinstance(values, list) else [values]:
                if v not in vocab:
                    errors.append("%s: %s value %r is not in the vocabulary" % (rel, key, v))
        if human:
            if "qualities" in fm:
                errors.append("%s: human-in-the-loop cards have no qualities" % rel)
            sections = ("## Loop", "## Getting a good signal", "## When and how long", "## Sources")
        else:
            if not fm.get("qualities"):
                errors.append("%s: no qualities" % rel)
            if any(k in fm for k in ("when", "initiator", "sync", "assesses")):
                errors.append("%s: axes belong to human-in-the-loop cards only" % rel)
            sections = ("## Loop", "## Set up", "## Sources")
        for section in sections:
            if section not in text:
                errors.append("%s: missing %s" % (rel, section))
        if not summary(text):
            errors.append("%s: empty Loop section" % rel)
    for path in CATALOG.rglob("*.md"):
        for link in re.findall(r"\]\(([^)#]+?\.(?:md|yaml))(?:#[^)]*)?\)", path.read_text(encoding="utf-8")):
            if not link.startswith("http") and not (path.parent / link).resolve().exists():
                errors.append("%s: broken link %s" % (path.relative_to(CATALOG), link))
    readme = (CATALOG / "README.md").read_text(encoding="utf-8")
    for path in cards():
        if "](%s)" % path.relative_to(CATALOG) not in readme:
            errors.append("README.md does not list %s" % path.relative_to(CATALOG))
    if not INDEX.exists() or INDEX.read_text(encoding="utf-8") != build_index():
        errors.append("index.yaml is out of date: run python3 scripts/catalog.py index")
    return errors


def main():
    cmd = sys.argv[1] if len(sys.argv) > 1 else ""
    if cmd == "index":
        INDEX.write_text(build_index(), encoding="utf-8")
        print("wrote %s (%d loop types)" % (INDEX, len(cards())))
    elif cmd == "check":
        errors = check()
        print("\n".join(errors) if errors else "OK: %d loop types" % len(cards()))
        sys.exit(1 if errors else 0)
    else:
        sys.exit(__doc__)


if __name__ == "__main__":
    main()
